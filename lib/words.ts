const EN_IDS = CATEGORIES.filter((c) => c.lang === "en" && c.id !== "random").map((c) => c.id);

export function getPool(id: string): string[] {
  if (id === "random") return Array.from(new Set(EN_IDS.flatMap((k) => BANKS[k])));
  return BANKS[id] ?? BANKS.general;
}

export const isFilipino = (id: string) => CATEGORIES.find((c) => c.id === id)?.lang === "fil";
